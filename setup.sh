#!/usr/bin/env bash
# Pinned Linux x86-64 release and mainline-format model. Interrupted downloads resume.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p .runtime
cd .runtime
exec 9>.setup.lock
if ! flock -n 9; then
    echo 'Setup is busy. Stop the model with ./scripts/service stop (or stop the foreground launcher) and wait for any other setup to finish.' >&2
    exit 1
fi
tag=b12602
variant=bin-ubuntu-cuda-12.8-x64
release=https://github.com/ggml-org/llama.cpp/releases/download/$tag
fetch() {
    local path=$1 url=$2 checksum=$3
    if [[ ! -f $path ]]; then
        curl --fail --location --retry 3 --continue-at - --output "$path.part" "$url"
        echo "$checksum  $path.part" | sha256sum -c -
        mv "$path.part" "$path"
    else
        echo "$checksum  $path" | sha256sum -c -
    fi
}
# Binary, driver libraries, reference weights and source are independent downloads.
pids=()
fetch llama.tar.gz "$release/llama-$tag-$variant.tar.gz" 8228a1df09044467cfa3e800974925fc1f84c55b8fcd277ea0fb1e8f7833b647 &
pids+=("$!")
fetch cudart.tar.gz "$release/cudart-llama-$tag-$variant.tar.gz" 2d2eb524e375ae68ed9c17b9c0a3523acca3067a64cc4617c7b90476314070e7 &
pids+=("$!")
python3 ../checkpoints.py "${INKLING_VARIANT:-reference}" &
pids+=("$!")
fetch source.tar.gz "https://codeload.github.com/ggml-org/llama.cpp/tar.gz/refs/tags/$tag" 5b21f4b4d79aeca37bf7e07d853fc314f4889930a977d511a977b9b6b5949622 &
pids+=("$!")
failed=0
for pid in "${pids[@]}"; do wait "$pid" || failed=1; done
if ((failed)); then exit 1; fi

mkdir -p "llama-$tag"
rm -f "llama-$tag/.inkling-ready"
tar -xzf llama.tar.gz
tar -xzf cudart.tar.gz
# b12602 predates ggml-org/llama.cpp#32704.
tar -xzf source.tar.gz
patch -d "llama.cpp-$tag" -p1 < ../inkling-loop-scales.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-depth-mix.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-mask-layout.patch
patch -d "llama.cpp-$tag" -p1 < ../shared-expert-cache.patch
patch -d "llama.cpp-$tag" -p1 < ../cuda-buffer-budget.patch
patch -d "llama.cpp-$tag" -p1 < ../gpu-experts.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-query-tiles.patch
patch -d "llama.cpp-$tag" -p1 < ../compact-expert-cache.patch
# This header is generated by the next patch. The upstream tarball omits it.
rm -f "llama.cpp-$tag/src/inkling-host-global-kv.h"
patch -d "llama.cpp-$tag" -p1 < ../inkling-host-global-kv.patch
patch -d "llama.cpp-$tag" -p1 < ../estimate-graph-placement.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-stage-global-kv.patch
# A repeat setup extracts upstream over the previous build, leaving generated headers.
rm -f "llama.cpp-$tag/src/inkling-relative-indices.h"
patch -d "llama.cpp-$tag" -p1 < ../inkling-relative-indices.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-phase-cache.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-decode-budget.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-prompt-lookup.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-compact-fa.patch
# The source archive omits generated files; remove just these exact patch outputs on repeat builds.
rm -f "llama.cpp-$tag/src/inkling-elastic-kv.cpp" "llama.cpp-$tag/src/inkling-elastic-kv.h"
patch -d "llama.cpp-$tag" -p1 < ../inkling-elastic-kv.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-controller.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-shortconv.patch
install -m 644 ../native/expert-transfer/inkling-{expert-upload,slot-wait}.h "llama.cpp-$tag/ggml/include/"
patch -d "llama.cpp-$tag" -p1 < ../inkling-expert-transfers.patch
install -m 644 ../native/expert-transfer/inkling-device-routes.h "llama.cpp-$tag/ggml/include/"
patch -d "llama.cpp-$tag" -p1 < ../inkling-device-routes.patch
patch -d "llama.cpp-$tag" -p1 < ../inkling-graph-routes.patch
# NixOS can have a newer default compiler than the loader for upstream binaries.
if [[ -e /etc/NIXOS && -n ${NIX_LD:-} && -z ${CC:-} ]]; then
    loader_lib=$(dirname "$(readlink -f "$NIX_LD")")
    for wrapper in /nix/store/*-gcc-wrapper-*/nix-support/orig-libc; do
        if [[ -f $wrapper && $(cat "$wrapper")/lib == "$loader_lib" ]]; then
            toolchain=${wrapper%/nix-support/*}
            export CC="$toolchain/bin/gcc" CXX="$toolchain/bin/g++"
            break
        fi
    done
fi
ninja=$(command -v ninja || true)
if [[ -z $ninja && -d /nix/store ]]; then
    for binary in /nix/store/*-ninja-*/bin/ninja; do
        if [[ -x $binary ]]; then ninja=$binary; break; fi
    done
fi
cmake -S "llama.cpp-$tag" -B model-build -G Ninja -DCMAKE_MAKE_PROGRAM="${ninja:?Install ninja}" \
    -DLLAMA_INKLING_VMM="${INKLING_BUILD_ELASTIC_KV:-AUTO}" \
    -DBUILD_SHARED_LIBS=ON -DGGML_BACKEND_DL=ON -DGGML_NATIVE=OFF \
    -DLLAMA_BUILD_COMMON=OFF -DLLAMA_BUILD_TOOLS=OFF -DLLAMA_BUILD_TESTS=OFF \
    -DLLAMA_BUILD_EXAMPLES=OFF -DLLAMA_BUILD_SERVER=OFF -DGGML_CCACHE=OFF
cmake --build model-build --target llama -j "${BUILD_JOBS:-8}"
cp model-build/bin/libllama.so.1.0.0 "llama-$tag/libllama.so.1.0.0.new"
mv "llama-$tag/libllama.so.1.0.0.new" "llama-$tag/libllama.so.1.0.0"
cp model-build/bin/libggml-base.so.1.0.0 "llama-$tag/libggml-base.so.1.0.0.new"
mv "llama-$tag/libggml-base.so.1.0.0.new" "llama-$tag/libggml-base.so.1.0.0"
echo gpu-experts-v8 > "llama-$tag/.inkling-ready"
